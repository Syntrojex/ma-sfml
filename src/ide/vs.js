'use strict';
const fs     = require('fs');
const path   = require('path');
const crypto = require('crypto');

const MAIN_CPP = [
  '#include <SFML/Graphics.hpp>',
  '#include <optional>',
  '',
  'int main() {',
  '    sf::RenderWindow window(sf::VideoMode({800u, 600u}), "SFML Project");',
  '    window.setFramerateLimit(60);',
  '',
  '    while (window.isOpen()) {',
  '        while (const std::optional event = window.pollEvent()) {',
  '            if (event->is<sf::Event::Closed>())',
  '                window.close();',
  '        }',
  '',
  '        window.clear(sf::Color::Black);',
  '        window.display();',
  '    }',
  '    return 0;',
  '}',
].join('\n');

function guid() { return crypto.randomUUID().toUpperCase(); }
function safeNamespace(name) { return name.replace(/[^\w]+/g, '') || 'SFMLProject'; }

// ── ma-sfml.props ─────────────────────────────────────────────────────────────
// Uses the ABSOLUTE path of the SFML directory so the props file can live
// anywhere and still resolve correctly — no $(SolutionDir) guesswork needed.
function propsContent(sfmlPath) {
  const s = sfmlPath.replace(/\//g, '\\');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Auto-generated by ma-sfml — do not edit manually. -->
<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">

  <PropertyGroup Label="ma-sfml">
    <SfmlDir>${s}</SfmlDir>
  </PropertyGroup>

  <ItemDefinitionGroup>
    <ClCompile>
      <AdditionalIncludeDirectories>$(SfmlDir)\\include;%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>
    </ClCompile>
    <Link>
      <AdditionalLibraryDirectories>$(SfmlDir)\\lib;%(AdditionalLibraryDirectories)</AdditionalLibraryDirectories>
      <AdditionalDependencies Condition="'$(Configuration)'=='Debug'"
        >sfml-graphics-d.lib;sfml-window-d.lib;sfml-system-d.lib;sfml-audio-d.lib;sfml-network-d.lib;%(AdditionalDependencies)</AdditionalDependencies>
      <AdditionalDependencies Condition="'$(Configuration)'!='Debug'"
        >sfml-graphics.lib;sfml-window.lib;sfml-system.lib;sfml-audio.lib;sfml-network.lib;%(AdditionalDependencies)</AdditionalDependencies>
    </Link>
    <PostBuildEvent>
      <!-- Copy SFML DLLs to output folder so the .exe finds them at runtime -->
      <Command>xcopy /Y /I "$(SfmlDir)\\bin\\*.dll" "$(OutDir)"</Command>
      <Message>Copying SFML DLLs to output directory</Message>
    </PostBuildEvent>
  </ItemDefinitionGroup>

</Project>
`;
}

