// ── Inject <Import> into existing .vcxproj ────────────────────────────────────
function injectPropsImport(vcxFile, propsAbsPath) {
  try {
    let content = fs.readFileSync(vcxFile, 'utf8');
    if (content.includes('ma-sfml.props')) {
      // Already injected — just update the path in case SFML moved
      content = content.replace(/<Import Project="[^"]*ma-sfml\.props"[^/]*\/>/,
        `<Import Project="${propsAbsPath.replace(/\\/g, '\\\\')}" />`);
    } else {
      // Use the ABSOLUTE path so VS can always find it regardless of folder structure
      content = content.replace('</Project>',
        `  <!-- ma-sfml: SFML include, lib, and DLL paths -->\n  <Import Project="${propsAbsPath.replace(/\\/g, '\\\\')}" />\n</Project>`);
    }
    fs.writeFileSync(vcxFile, content, 'utf8');
  } catch (e) {
    throw new Error('Could not update .vcxproj: ' + e.message);
  }
}

// ── Main export ───────────────────────────────────────────────────────────────
module.exports = function linkVs(projectDir, sfmlPath, projectName, opts = {}) {
  const { createProject = false, vcxprojPath = null } = opts;
  const files = [];

  if (createProject) {
    // New project — vcxproj and props both live in projectDir
    const projGuid  = guid();
    const propsFile = path.join(projectDir, 'ma-sfml.props');
    const vcxFile   = path.join(projectDir, `${projectName}.vcxproj`);
    const slnFile   = path.join(projectDir, `${projectName}.sln`);
    const srcDir    = path.join(projectDir, 'src');

    fs.writeFileSync(propsFile, propsContent(sfmlPath), 'utf8');
    fs.writeFileSync(vcxFile, vcxprojContent(projectName, projGuid, 'ma-sfml.props'), 'utf8');
    fs.writeFileSync(slnFile, slnContent(projectName, projGuid), 'utf8');

    if (!fs.existsSync(srcDir)) fs.mkdirSync(srcDir, { recursive: true });
    const mainCpp = path.join(srcDir, 'main.cpp');
    if (!fs.existsSync(mainCpp)) fs.writeFileSync(mainCpp, MAIN_CPP, 'utf8');

    files.push('ma-sfml.props', `${projectName}.vcxproj`, `${projectName}.sln`, 'src/main.cpp');

    return {
      files,
      manifest: {
        ide: 'vs',
        propsFile,
        vcxprojPath: vcxFile,
        configFiles: ['ma-sfml.props', `${projectName}.vcxproj`, `${projectName}.sln`],
        stub: 'src/main.cpp',
      },
    };

  } else if (vcxprojPath) {
    // Existing project — place props NEXT TO the .vcxproj (same directory)
    // Then inject the ABSOLUTE path into the .vcxproj so VS always finds it,
    // regardless of how deep the .vcxproj is nested relative to the .sln.
    const vcxDir    = path.dirname(vcxprojPath);
    const propsFile = path.join(vcxDir, 'ma-sfml.props');

    fs.writeFileSync(propsFile, propsContent(sfmlPath), 'utf8');
    injectPropsImport(vcxprojPath, propsFile);

    files.push(
      path.relative(projectDir, propsFile).replace(/\\/g, '/') + '  (created)',
      path.relative(projectDir, vcxprojPath).replace(/\\/g, '/') + '  (updated)',
    );

    return {
      files,
      manifest: {
        ide: 'vs',
        propsFile,
        vcxprojPath,
        configFiles: [path.relative(projectDir, propsFile).replace(/\\/g, '/')],
        stub: null,
      },
    };

  } else {
    throw new Error('No .vcxproj found. Run from inside your Visual Studio project folder.');
  }
};
